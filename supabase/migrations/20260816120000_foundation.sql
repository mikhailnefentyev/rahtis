-- RAHTIS · Этап 1 · фундамент
--
-- Схема app для служебных функций и перечисления домена.
--
-- Хелперы RLS сюда не входят: они читают public.profiles, а функции на
-- LANGUAGE sql проверяются при создании — до появления таблицы такая
-- функция не создастся. Порядок в итоге такой:
--   фундамент → companies → profiles → хелперы и политики → журнал.
-- Таблицы при этом закрываются RLS сразу при создании, поэтому окна,
-- в котором данные доступны без политик, не возникает.
-- ═══════════════════════════════════════════════════════════════════

create schema if not exists app;

comment on schema app is
  'Служебные функции платформы: хелперы RLS, триггеры. Данные живут в public.';

-- Доступ к самой схеме открыт вошедшим, к таблицам в public — нет.
grant usage on schema app to authenticated, service_role;


-- ── Перечисления ───────────────────────────────────────────────────

/*
 * Роль стороны. Одним типом описываются и пользователи, и компании:
 * компания выступает перевозчиком или заказчиком, пользователь — ещё и
 * администратором платформы.
 *
 * Общий тип нужен не для экономии. Он позволяет связать профиль с
 * компанией составным внешним ключом (company_id, role) → (id, kind),
 * и тогда база сама не даст завести перевозчика в компании заказчика —
 * без единого триггера.
 */
create type public.party_role as enum ('CARRIER', 'SHIPPER', 'ADMIN');

comment on type public.party_role is
  'Роль стороны. Для компаний значение ADMIN запрещено ограничением.';

/*
 * Жизненный цикл компании (ТЗ §3).
 *
 *   PENDING  — заявка подана, оператор ещё не смотрел;
 *   APPROVED — Y-tunnus проверен, доступ выдан, но кабинет неполный:
 *              заказчик дозаполняет реквизиты, перевозчик — документы
 *              и карточки авто;
 *   ACTIVE   — компания работает;
 *   REJECTED — отказ.
 *
 * Открытой регистрации нет: заявка и есть компания в статусе PENDING.
 * Отдельной таблицы заявок нет намеренно — иначе появился бы шаг
 * «сконвертировать заявку в компанию», способный упасть на середине,
 * а правило «один Y-tunnus = один кабинет» начинало бы действовать
 * только после одобрения.
 */
create type public.company_status as enum ('PENDING', 'APPROVED', 'ACTIVE', 'REJECTED');


-- ── Общие триггеры ─────────────────────────────────────────────────

create or replace function app.touch_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

comment on function app.touch_updated_at() is
  'Обновляет updated_at при каждом UPDATE. Вешается на все таблицы с этой колонкой.';
