-- ═══════════════════════════════════════════════════════════════════
-- RAHTIS · отметку точки снимают только сразу
--
-- uncomplete_stop снимал отметку с последней пройденной точки без срока.
-- После правила «после первой пройденной точки рейс не отменяется»
-- (55012) это стало лазейкой: перевозчик снимал отметку забора, и отказ
-- от рейса снова принимался — заказ с уже забранным прицепом возвращался
-- на общий стол (прогон 13.10.2026).
--
-- Решение пользователя 13.10.2026: отметку снимают в течение 15 минут
-- после нажатия — ошибочное нажатие исправляется сразу; позже отметку
-- снимает только оператор. Свой код 55014 — кабинет отвечает на него
-- отдельной фразой. Текст функции берётся из базы и меняется точечно.
-- ═══════════════════════════════════════════════════════════════════

do $$
declare
  v_def text := replace(pg_get_functiondef('public.uncomplete_stop(uuid)'::regprocedure), E'\r\n', E'\n');
  v_mark text := '  update public.order_stops';
  v_new text;
begin
  if (length(v_def) - length(replace(v_def, v_mark, ''))) / length(v_mark) <> 1 then
    raise exception 'uncomplete_stop: место правки не найдено или встретилось не один раз';
  end if;

  v_new := replace(
    v_def,
    v_mark,
    $r$  if not (select app.is_admin())
     and v_stop.completed_at < now() - interval '15 minutes' then
    raise exception 'Отметку можно снять в течение 15 минут, позже — через оператора.' using errcode = '55014';
  end if;

  update public.order_stops$r$
  );

  execute v_new;
end;
$$;
