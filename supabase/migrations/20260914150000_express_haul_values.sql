-- RAHTIS · в перечислении единиц появляются фургон и грузовик
--
-- Отдельная миграция ровно из одной причины: Postgres не даёт
-- пользоваться значением перечисления в той же транзакции, в которой оно
-- добавлено. Всё, что опирается на VAN и TRUCK — ограничения, подбор
-- машины, проверки публикации, — живёт в следующей миграции, и иначе
-- быть не может.
--
-- ПОЧЕМУ ЭТО ТА ЖЕ ОСЬ, А НЕ НОВАЯ.
--
-- haul_kind отвечает на вопрос «чем выполняется рейс», и заказчик
-- отвечает на него одним выбором из четырёх: полуприцеп, контейнер,
-- микроавтобус, грузовик. Витрина, бейдж единицы, карточка рассылки и
-- подписи точек уже читают это одно поле — в коде на него заведено семь
-- мест и написано, что «третий тип единицы добавляется одним блоком».
-- Завести экспресс вторым полем значило бы заставить каждый из этих
-- экранов читать два и выбирать, какое главнее.
--
-- Прежний комментарий к типу говорил «что тянут». Для фургона это
-- неверно: груз едет внутри, а не за машиной. Формулировка исправлена
-- здесь же, потому что она и есть определение оси.
-- ═══════════════════════════════════════════════════════════════════

alter type public.haul_kind add value if not exists 'VAN';
alter type public.haul_kind add value if not exists 'TRUCK';

comment on type public.haul_kind is
  'Чем выполняется рейс: полуприцеп, контейнер, микроавтобус или грузовик. Форма рейса — отдельная ось, order_type.';
