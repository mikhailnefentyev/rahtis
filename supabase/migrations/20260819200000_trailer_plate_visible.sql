-- RAHTIS · номер прицепа возвращается заказчику
--
-- Починка того, о чём предупреждала миграция carrier_anonymity:
-- «новая колонка не станет видимой сама собой, её придётся дописать сюда
-- руками — то есть подумав». Колонку trailer_plate добавили, а в
-- поимённый грант не дописали.
--
-- Последствие оказалось шире, чем «не видно номера прицепа». Postgres
-- отказывает не в колонке, а в запросе целиком: карточка заказчика
-- просит trailer_plate в списке колонок и получает «permission denied
-- for table orders», то есть НИ ОДНОГО заказа. В интерфейсе это выглядело
-- как «Заказов пока нет» у компании с двумя заказами — сообщение, из
-- которого причину не угадать.
--
-- Перевозчик этого не заметил: он читает рейсы через my_assignments и
-- стол через desk_orders, а функциям с security definer колоночные
-- гранты не помеха.
--
-- commission_bps и closed_at из соседней миграции сюда намеренно не
-- попадают. Комиссия — доля оператора в расчётах с перевозчиком, и
-- заказчику она не видна ни грантом, ни типом; отчёты Этапа 7 читают её
-- функциями, где состав колонок записан явно.
-- ═══════════════════════════════════════════════════════════════════

grant select (trailer_plate) on public.orders to authenticated;

comment on column public.orders.trailer_plate is
  'Номер прицепа. Виден обеим сторонам: по нему водитель находит железо на площадке.';
