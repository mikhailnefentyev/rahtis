-- RAHTIS · чистка закрытых инцидентов по расписанию
--
-- PRIVACY 8.3 обещает: закрытые записи о сбоях удаляются через 90 дней
-- после последнего повторения. Функция prune_incidents есть с 28.08, но
-- её никто не вызывал — ни задание cron, ни маршрут. Найдено сверкой
-- документов с поведением 29.09.2026. Открытые сбои не трогаются.
-- ═══════════════════════════════════════════════════════════════════

/* 03:45 UTC — после остальных чисток (03:20–03:50). */
select cron.schedule(
  'rahtis-incidents-retention',
  '45 3 * * *',
  $$ select public.prune_incidents(90); $$
);
