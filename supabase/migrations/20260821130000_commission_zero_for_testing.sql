-- RAHTIS · комиссия 0% на время проверки
--
-- ВРЕМЕННО. По ТЗ §1 комиссия оператора 3%, и вернуть её нужно до того,
-- как по платформе пойдут настоящие деньги.
--
-- Меняется тело одной функции — ровно затем она и заводилась. Двух
-- десятков мест, где считаются деньги, эта правка не касается: отчёты,
-- счета и выплаты спрашивают ставку у неё.
--
-- Что при этом НЕ меняется — уже закрытые рейсы. У каждого своя ставка
-- записана в orders.commission_bps в момент закрытия, и отчёты считают по
-- ней. Поэтому рейсы, закрытые до сегодня, останутся с 3%, а закрытые
-- после — с нулём, и когда ставка вернётся, ни один из них не пересчитают
-- задним числом. Это и есть смысл замороженной ставки.
--
-- Исключение — рейсы, закрытые до появления самой колонки: у них ставки
-- нет вовсе, и app.order_bps подставляет действующую. Их отчёты станут
-- считаться по нулю, а после возврата 3% — снова по трём процентам.
-- Таких рейсов ровно столько, сколько было закрыто до 21.08.2026.
-- ═══════════════════════════════════════════════════════════════════

