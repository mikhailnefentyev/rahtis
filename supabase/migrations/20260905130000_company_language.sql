-- RAHTIS · у компании появляется язык переписки
--
-- Письма платформы были финскими жёстко: EMAIL_LOCALE = 'fi', и рядом
-- пометка «рынок финский, английский кабинет существует для тех, кто
-- читает интерфейс, а не для переписки». Это было верно, пока рынок
-- действительно был финским.
--
-- Теперь платформа зовёт датских и норвежских экспедиторов. Они получат
-- по-фински всё: приглашение с кодами доступа, восстановление пароля,
-- недельный отчёт, уведомление о снятом рейсе. И если у кабинета есть
-- переключатель языка, то у письма его нет — человек просто не поймёт,
-- что ему прислали.
--
-- Язык хранится у компании, а не у пользователя. Переписка платформы
-- ведётся с юридическим лицом: приглашение, счёт, отчёт адресованы
-- компании, а не тому, кто в ней сегодня сидит за экраном. Коллеги в
-- одной компании читают одни и те же письма.
--
-- Умолчание финское, и это не про язык, а про историю: все заведённые до
-- сих пор компании финские, и переписка с ними уже идёт по-фински.
-- Приписать им английский задним числом значило бы сменить язык разговора
-- посреди него.
--
-- Значение проставляется из локали формы заявки: человек уже выбрал, на
-- каком языке ему читать, когда заполнял её. Спрашивать второй раз о том,
-- на что он уже ответил, — плохой способ собрать данные.
-- ═══════════════════════════════════════════════════════════════════

alter table public.companies
  add column language text not null default 'fi',

  add constraint companies_language_supported
    check (language in ('fi', 'en'));

comment on column public.companies.language is
  'Язык переписки с компанией. Из локали формы заявки; интерфейс каждый выбирает сам.';

/*
 * Грант только на запись.
 *
 * Чтение у companies выдано на таблицу целиком, поэтому новая колонка
 * видна сама — в отличие от orders, где права поимённые и добавленная
 * колонка дважды роняла всю страницу заказчика.
 *
 * А вот запись здесь как раз поимённая: компания может менять name и
 * contact_email, остальное — через функции оператора. Язык переписки это
 * решение самой компании, а не предмет обращения в поддержку, поэтому он
 * добавляется к тому же короткому списку.
 */
grant update (language) on public.companies to authenticated;
