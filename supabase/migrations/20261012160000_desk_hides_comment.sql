-- ═══════════════════════════════════════════════════════════════════
-- RAHTIS · стол не показывает комментарий заказа до назначения
--
-- Условия (п. 6.8) обещают заказчику, что заметки к заказу перевозчик
-- видит только после назначения. Заметки точек стол уже скрывал, а
-- общий комментарий заказа отдавал всем, кому виден заказ: в него
-- пишут имена получателей, телефоны и коды ворот (прогон 12.10.2026).
--
-- Колонка в ответе остаётся — пустой: назначенный перевозчик читает
-- комментарий в карточке рейса (my_assignments), водитель — в задании.
-- ═══════════════════════════════════════════════════════════════════

do $$
declare
  v_def text := replace(pg_get_functiondef('public.desk_orders(text, integer)'::regprocedure), E'\r\n', E'\n');
  v_new text;
begin
  v_new := regexp_replace(v_def, '(\n\s+)o\.comment,', '\1null::text,');

  if v_new = v_def then
    if position('null::text,' in v_def) = 0 then
      raise exception 'desk_orders: место правки не найдено';
    end if;
    return;
  end if;

  execute v_new;
end;
$$;
