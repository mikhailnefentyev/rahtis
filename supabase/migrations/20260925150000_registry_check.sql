-- RAHTIS · сверка заявки с реестром PRH
--
-- При подаче заявки сервер запрашивает открытые данные PRH/YTJ: название,
-- состояние компании, ennakkoperintärekisteri и ALV. Итог приходит
-- оператору в письме о заявке и виден в очереди модерации; заявитель
-- сразу видит, нашёлся ли Y-tunnus. Одобряет по-прежнему человек
-- (решение пользователя от 25.09.2026).
--
-- Хранится снимок ответа, а не ссылка на реестр: оператор решает по тому,
-- что было на момент заявки, и при разборе «почему одобрили» видно, что
-- именно он видел. Перепроверка из админки перезаписывает снимок.
--
-- Колонку пишет только сервер секретным ключом: колоночного гранта на
-- update у authenticated нет. Читать её компании не запрещено — это
-- публичные данные реестра о ней самой.
-- ═══════════════════════════════════════════════════════════════════

alter table public.companies
  add column registry_check jsonb;

comment on column public.companies.registry_check is
  'Снимок сверки с открытыми данными PRH на момент заявки или перепроверки: вердикт, название в реестре, ennakkoperintä, ALV, замечания.';
