-- RAHTIS · заказчик снова видит свои заказы
--
-- Ровно то, о чём предупреждала миграция trailer_plate_visible: «новая
-- колонка не станет видимой сама собой, её придётся дописать сюда руками
-- — то есть подумав». Колонки haul_kind и container_feet добавили, в
-- поимённый грант не дописали, и предупреждение сработало во второй раз.
--
-- Последствие шире, чем «не видно типа единицы». Postgres отказывает не в
-- колонке, а в запросе целиком: страница заказчика просит haul_kind в
-- списке колонок и получает «permission denied for table orders», то есть
-- НИ ОДНОГО заказа. В интерфейсе это выглядит как «Заказов пока нет» у
-- компании с заказами — сообщение, из которого причину не угадать.
--
-- Перевозчик этого снова не заметил: он читает стол через desk_orders и
-- рейсы через my_assignments, а функциям с security definer колоночные
-- гранты не помеха. Поэтому контейнер на столе был виден, а в кабинете
-- заказчика пропали все заказы разом.
--
-- Обе колонки видны обеим сторонам по существу: что тянут и какого
-- размера — это условие работы, а не чья-то коммерческая тайна.
-- ═══════════════════════════════════════════════════════════════════

grant select (haul_kind, container_feet) on public.orders to authenticated;

comment on column public.orders.haul_kind is
  'Полуприцеп или контейнер. Видно обеим сторонам: от этого зависит, какая машина подойдёт.';
