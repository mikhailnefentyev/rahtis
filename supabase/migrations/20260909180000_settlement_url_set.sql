-- RAHTIS · адрес выпуска документов периода заведён
--
-- Предыдущая попытка вывести его из reports_url не сработала: там записан
-- не тот путь, который я предположил, и настройка осталась пустой. Узнал
-- об этом сразу — пульс показал settlement_not_configured = 1, — а не
-- первого числа, когда документы не выпустились бы молча.
--
-- Поэтому адрес задан прямо и от корня сайта, а не выведен из соседней
-- строки: вывод, опирающийся на форму чужого значения, ломается ровно
-- тогда, когда это значение меняют.
--
-- on conflict do update: строка могла появиться заведённой руками с
-- неверным путём, и оставить её значило бы держать расписание молчащим.
-- ═══════════════════════════════════════════════════════════════════

insert into app.runtime_config (key, value, note)
values (
  'settlement_url',
  'https://www.rahtis.eu/api/reports/settlement',
  'Куда стучится задание документов расчётного периода, первого и шестнадцатого числа.'
)
on conflict (key) do update
  set value = excluded.value,
      note = excluded.note,
      updated_at = now();
