-- RAHTIS · журнал заказа перестаёт быть журналом одних точек
--
-- Отдельным файлом ради одного: значение, добавленное в enum, нельзя
-- использовать в той же транзакции, в которой оно добавлено. Миграции
-- применяются по одной транзакции на файл, поэтому расширение типа
-- живёт здесь, а всё, что им пользуется, — в следующем файле.
--
-- Почему вообще в этот журнал, а не в новую таблицу: заказчику и
-- перевозчику нужна одна лента «что случилось с рейсом», а не три. Смена
-- цены, снятие заказа и отказ перевозчика — события того же порядка, что
-- перенесённая выгрузка, и читаются они рядом с ней или не читаются
-- вовсе.
-- ═══════════════════════════════════════════════════════════════════

/* Пробег и ставка пересчитаны: маршрут стал другой длины. */
alter type public.amendment_kind add value if not exists 'ORDER_REPRICED';

/* Заказ снят: заказчиком или оператором, с причиной. */
alter type public.amendment_kind add value if not exists 'ORDER_CANCELLED';

/*
 * Перевозчик отказался от взятого рейса, и заказ вернулся на стол.
 * Отдельно от снятия: заказ жив, работа продолжается, сменился
 * исполнитель. Для рейтинга это разные события.
 */
alter type public.amendment_kind add value if not exists 'ORDER_RELEASED';
