-- RAHTIS · уведомление об отчёте ведёт к отчёту
--
-- «Viikkoraportti · valmiit kuljetukset · Viikko 36 · Avaa →» открывало
-- раздел выполненных рейсов. Отчёта там нет: он лежит отдельным файлом
-- в архиве на первом экране кабинета, и найти его человек должен был
-- сам. Уведомление обещало отчёт, а приводило к списку.
--
-- Впредь ссылку ставит генератор отчётов. Здесь чинятся уже выпущенные:
-- строка отчёта находится по компании, роли и моменту выпуска — он
-- отличается от времени уведомления на доли секунды, потому что
-- уведомление и создаётся сразу после записи.
--
-- Роль берётся из самой ссылки: у выпущенных уведомлений это
-- единственное место, где она сохранилась.
-- ═══════════════════════════════════════════════════════════════════

update public.notifications n
set link = '/reports/' || r.id
from public.weekly_reports r
where n.kind = 'REPORT'
  and n.link in ('/carrier/done', '/shipper/done')
  and r.company_id = n.company_id
  and r.role = (case when n.link = '/carrier/done' then 'CARRIER' else 'SHIPPER' end)::public.party_role
  /* Окно намеренно узкое: недельные отчёты одной компании выпускаются раз в неделю. */
  and r.generated_at between n.created_at - interval '5 minutes' and n.created_at + interval '5 minutes';
