-- ═══════════════════════════════════════════════════════════════════
-- RAHTIS · ставка незакрытого рейса знает сторону договора
--
-- app.order_bps подставляла действующие 3 % всякому рейсу, у которого
-- ставка ещё не заморожена, — то есть любому незакрытому. У рейса
-- своего клиента подписчика процента нет и не будет, но до закрытия он
-- показывался: в сводках, у агента, в расчётах выплаты. Перевозчику
-- обещалась выплата меньше той, что он получит, а оператору — доход,
-- которого не случится.
--
-- Закрытые рейсы это не трогает: у них ставка записана в самом рейсе,
-- и coalesce до второго аргумента не доходит.
-- ═══════════════════════════════════════════════════════════════════

create or replace function app.order_bps(p_order public.orders)
returns integer
language sql
stable
as $$
  select coalesce(
    p_order.commission_bps,
    case
      when p_order.contract_party = 'CARRIER' then 0
      else app.current_commission_bps()
    end
  );
$$;

comment on function app.order_bps(public.orders) is
  'Плата перевозчика по рейсу: замороженная при закрытии, иначе действующая — и ноль там, где договор не наш.';
