-- RAHTIS · Этап 5 · уборка просроченной брони по расписанию
--
-- Правильность от этого расписания не зависит: истёкшая бронь снимается
-- при любом действии над заказом, а стол показывает такой заказ
-- свободным. Планировщик нужен, чтобы заказ возвращался на стол сам, без
-- чьего-либо действия, и чтобы у уведомлений Этапа 8 был повод сработать.
--
-- Раз в минуту — компромисс: срок решения по ТЗ §6 составляет пятнадцать
-- минут, и минутная точность уборки на этом фоне незаметна.
-- ═══════════════════════════════════════════════════════════════════

create extension if not exists pg_cron with schema extensions;

/*
 * Задания pg_cron всегда живут в схеме cron независимо от того, куда
 * установлено само расширение: имя схемы прошито в нём самом.
 */
do $$
begin
  perform cron.unschedule('rahtis-expire-order-deadlines');
exception
  when others then
    /* Задания ещё не было — это нормально при первом применении. */
    null;
end;
$$;

select cron.schedule(
  'rahtis-expire-order-deadlines',
  '* * * * *',
  $$ select public.expire_order_deadlines(); $$
);
