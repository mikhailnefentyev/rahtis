-- RAHTIS · база машины — город, а не адрес площадки
--
-- 8.10.2026: на карте транспорта Ханко стоял двумя строками — «Hanko» и
-- «Hangon satama — Korsmaninkatu 6, 10900 Hanko». Подсказка адреса
-- предлагала порт, и в base_city ложился весь адрес. Форма теперь берёт
-- город из подсказки; здесь — уже записанные адреса: город после
-- почтового индекса.
-- ═══════════════════════════════════════════════════════════════════

update public.vehicles
set base_city = btrim(substring(base_city from '\d{5}\s+([^,]+)$'))
where base_city ~ '\d{5}\s+[^,]+$';
