-- RAHTIS · размер парка для главной страницы
--
-- На первом экране стоит живое число: сколько машин имеет допуск прямо
-- сейчас. Читать его напрямую из vehicles посетитель не может и не
-- должен — RLS закрывает таблицу от анонима целиком, и счётчик молча не
-- рисовался. Молча — худший из возможных исходов: страница выглядит
-- исправной, а цифры, ради которой всё затевалось, на ней нет.
--
-- Наружу отдаются ровно два агрегата и ничего больше: сколько машин и в
-- скольких городах они стоят. Ни номеров, ни компаний, ни водителей —
-- посетителю нужно знать, что перевозчики есть, а не кто они.
--
-- Считаются машины с допуском, а не все заведённые. Машина без допуска
-- на стол не выходит и груз не увезёт, так что для заказчика это
-- единственное осмысленное количество, а для перевозчика — честное:
-- видно реальных конкурентов, а не число заполненных анкет.
-- ═══════════════════════════════════════════════════════════════════

create or replace function public.fleet_size()
returns table (vehicles integer, regions integer)
language sql
stable
security definer
set search_path = ''
as $$
  select
    count(*)::integer,
    count(distinct base_city)::integer
  from public.vehicles
  where access = 'APPROVED';
$$;

comment on function public.fleet_size() is
  'Размер допущенного парка для главной страницы: только два агрегата, доступно без входа.';

revoke all on function public.fleet_size() from public;
grant execute on function public.fleet_size() to anon, authenticated, service_role;
