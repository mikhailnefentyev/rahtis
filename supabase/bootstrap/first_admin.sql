-- RAHTIS · первый администратор
--
-- Курица и яйцо: заявки одобряет администратор, а завести администратора
-- некому, пока его нет. Этот скрипт разрывает круг.
--
-- Почему не миграция. Миграции описывают схему и применяются одинаково
-- к любому окружению — локальному, тестовому, боевому. Конкретный адрес
-- первого администратора у каждого окружения свой, и зашивать его в
-- миграцию значит завести в тестовой базе администратора с боевой почтой.
-- Поэтому это разовый скрипт, выполняемый руками.
--
-- ── Как запустить ──────────────────────────────────────────────────
--
--   1. Панель Supabase → Authentication → Users → Add user.
--      Задайте почту и пароль, галку «Auto Confirm User» включите.
--      Профиль при этом НЕ создастся: триггер on_auth_user_created
--      пропускает пользователей без роли в app_metadata — а у заведённых
--      руками её нет.
--
--   2. Впишите ту же почту ниже вместо ЗАМЕНИТЕ_НА_ПОЧТУ.
--
--   3. Панель → SQL Editor → вставить и выполнить.
--
-- Скрипт идемпотентен: повторный запуск ничего не сломает.
-- ═══════════════════════════════════════════════════════════════════

do $$
declare
  -- ↓↓↓ ЕДИНСТВЕННОЕ, ЧТО НУЖНО ПОМЕНЯТЬ ↓↓↓
  v_email constant text := 'ЗАМЕНИТЕ_НА_ПОЧТУ';
  -- ↑↑↑ ────────────────────────────────── ↑↑↑

  v_user_id uuid;
begin
  if v_email = 'ЗАМЕНИТЕ_НА_ПОЧТУ' then
    raise exception
      'Впишите почту администратора в переменную v_email перед запуском.';
  end if;

  select id into v_user_id
  from auth.users
  where lower(email) = lower(btrim(v_email));

  /*
   * Молча ничего не делать нельзя: администратор не появится, а понятно
   * это станет только при первой попытке кого-то одобрить.
   */
  if v_user_id is null then
    raise exception
      'Пользователь % не найден. Сначала заведите его в Authentication → Users.',
      v_email;
  end if;

  insert into public.profiles (id, company_id, role)
  values (v_user_id, null, 'ADMIN')
  on conflict (id) do update
    set role = 'ADMIN',
        company_id = null;

  raise notice 'Администратор назначен: % (%)', v_email, v_user_id;
end;
$$;

