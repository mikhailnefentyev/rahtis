/**
 * Кладёт maplibre целиком в public/maplibre/ — тремя файлами рядом.
 *
 * Зачем это нужно.
 *
 * maplibre поставляется как самодостаточный набор: главный модуль, общий
 * модуль и воркер, который грузит тайлы и шрифты. Все три связаны
 * относительными импортами и путём, который воркер вычисляет через
 * import.meta.url.
 *
 * Сборщик Next разрезает этот набор по своим чанкам с хешированными
 * именами. Воркер он копирует побайтово в /_next/static/media/ вместе с
 * импортом "./maplibre-gl-shared.mjs" внутри, а сам общий модуль кладёт
 * туда же, но под именем с другим хешем — относительный импорт упирается
 * в 404. Если же указать воркеру путь на отдельную копию, он поднимется,
 * но загрузит СВОЙ экземпляр общего модуля, а главный поток продолжит
 * работать с бандловым: два разных экземпляра, и протокол между ними не
 * сходится.
 *
 * Ломается это молча и обманчиво: карта создаётся, стиль и спрайты
 * загружаются, контроллы и атрибуция на месте — а холст пустой. Ни одного
 * запроса тайла, события load и idle не наступают, в консоли чисто.
 * Единственный внешний признак — источники навсегда остаются
 * isSourceLoaded === false.
 *
 * Поэтому maplibre не бандлится вовсе: RouteMap подгружает главный модуль
 * прямо отсюда, а тот сам находит рядом и общий модуль, и воркер. Заодно
 * из клиентского бандла уходит около 950 КБ.
 *
 * Копирование скриптом, а не руками: иначе при обновлении maplibre в
 * public/ осталась бы версия от предыдущей, и расхождение вылезло бы
 * не там, где его будут искать.
 */
import { copyFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const from = join(root, 'node_modules', 'maplibre-gl', 'dist');
const to = join(root, 'public', 'maplibre');

/*
 * Порядок важен только для читателя: главный модуль и воркер оба
 * импортируют общий, и все трое обязаны лежать в одной папке.
 */
const files = ['maplibre-gl.mjs', 'maplibre-gl-shared.mjs', 'maplibre-gl-worker.mjs'];

await mkdir(to, { recursive: true });

for (const file of files) {
  await copyFile(join(from, file), join(to, file));
}

console.log(`maplibre: ${files.length} файла скопированы в public/maplibre/`);
