import { notFound } from 'next/navigation';

/**
 * Всё, что под языком и не совпало ни с одним маршрутом.
 *
 * Нужен для того, чтобы сработала своя страница 404. not-found.tsx
 * внутри сегмента показывается только когда notFound() вызван из этого
 * же сегмента; адрес, не совпавший ни с чем, до сегмента не доходит
 * вовсе — Next рисует встроенную заглушку «404: This page could not be
 * found.» по-английски, без шапки и без единой ссылки.
 *
 * Этот маршрут ловит такие адреса и вызывает notFound() уже изнутри
 * языка. Ничего не показывает сам: его работа — попасть в нужный
 * сегмент и передать управление соседнему not-found.tsx, у которого
 * есть словарь.
 *
 * Перехватывает он только то, что не разобрал никто другой: у
 * всеохватного маршрута самый низкий приоритет, и существующие адреса
 * он не заслоняет.
 */
export default function CatchAll(): never {
  notFound();
}
