/**
 * Адрес сайта для ссылок в письмах.
 *
 * Ссылка из письма живёт дольше письма: человек открывает её через час,
 * через день, с другого устройства. Она обязана вести на работающий
 * сайт, а не на машину, с которой письмо отправили.
 *
 * Порядок источников выстроен так, чтобы боевое письмо со ссылкой на
 * localhost стало невозможным. Именно это и случилось: письмо ушло с
 * ноутбука, где NEXT_PUBLIC_SITE_URL указывает на localhost, и кнопка в
 * ящике повела в никуда.
 *
 * VERCEL_PROJECT_PRODUCTION_URL подставляет сама площадка, и она права
 * по определению — это адрес, по которому приложение сейчас доступно.
 * Поэтому в бою он важнее переменной, которую человек мог не заполнить
 * или заполнить доменом, ещё не привязанным к проекту.
 */
export function siteUrl(): string {
  const configured = process.env.NEXT_PUBLIC_SITE_URL?.trim().replace(/\/$/, '');
  const local = configured?.startsWith('http://localhost');

  /* На площадке localhost не годится ни при каких настройках. */
  const onVercel = Boolean(process.env.VERCEL);

  if (configured && !(local && onVercel)) return configured;

  const production = process.env.VERCEL_PROJECT_PRODUCTION_URL;
  if (production) return `https://${production}`;

  /* Превью-развёртывание: свой адрес у каждого. */
  const deployment = process.env.VERCEL_URL;
  if (deployment) return `https://${deployment}`;

  return 'http://localhost:3000';
}

/**
 * Комиссия оператора в базисных пунктах: 300 bps = 3%.
 *
 * Хранится в bps, а не в долях, чтобы не тащить float в расчёты денег.
 * В будущем комиссия станет гибкой по клиентам и типам заказов — тогда это
 * значение станет дефолтом, а действующая ставка будет приходить из БД.
 *
 * ВАЖНО: при закрытии рейса действующая ставка фиксируется в самой записи рейса.
 * Отчёты и счета считают по зафиксированной ставке, а не по текущей — иначе
 * изменение комиссии перепишет задним числом уже выставленные счета.
 */
/*
 * С 23.09.2026 ставка 3 % — но только для рейсов, где сторона договора с
 * клиентом мы (orders.contract_party = 'RAHTIS'). У рейса своего клиента
 * подписчика она ноль: там мы не в деньгах. Решает это база при закрытии
 * рейса (app.freeze_order_fees), здесь — действующая ставка для оценок и
 * текстов кабинета.
 */
export const COMMISSION_BPS = 300;

/**
 * Ставка налога в базисных пунктах.
 *
 * Все суммы в системе — БЕЗ налога. Ставка заказчика, комиссия, выплата
 * перевозчику, недельные итоги: везде нетто. Налог добавляется в счёте,
 * а не в расчётах платформы, потому что ставка меняется решением
 * государства, а закрытые рейсы пересчитывать задним числом нельзя — по
 * той же причине, по которой комиссия замораживается в записи рейса.
 *
 * Ставка зависит от страны контрагента, а не одна на всех.
 *
 * Финская компания — обычная внутренняя продажа со ставкой 25,5%.
 * Иностранная — обратное начисление (käännetty verovelvollisuus): продавец
 * выставляет ноль, а налог в своей стране считает покупатель.
 *
 * Раньше здесь стоял ноль для всех, и это было верно ровно до первого
 * финского клиента. Комментарий на этом месте обещал, что «когда
 * понадобится разная по клиентам, ей место в карточке компании» — вот
 * этот момент и настал. Страна берётся из companies.country, заведённой
 * с первого дня.
 *
 * Ноль по-прежнему не совпадает с «налога нет»: у обратного начисления
 * налог есть, его считает покупатель, и документ обязан сказать об этом
 * словами, а не пустой строкой.
 */
export const VAT_BPS_FI = 2550;

/** Ставка налога для контрагента из страны. */
export function vatBpsFor(country: string | null | undefined): number {
  return country === 'FI' ? VAT_BPS_FI : 0;
}

/*
 * Срока оплаты заказчиком здесь больше нет.
 *
 * Он стоял тут как коммерческое условие рядом с комиссией, и это было
 * верно, пока его знал только выпуск документов. Но тот же срок называет
 * агент, а он живёт в базе и до config.ts не достаёт — и, не достав,
 * отвечал заказчику датой выплаты перевозчику.
 *
 * Теперь правило одно и лежит там, где его видят обе стороны:
 * app.invoice_due — конец расчётного периода плюс пятнадцать дней, рядом
 * с app.payout_due, где конец периода плюс тридцать.
 */

/**
 * Сумма с налогом — для счёта, не для расчётов платформы.
 *
 * Ставка обязательна и значения по умолчанию у неё нет: раньше здесь
 * стоял общий ноль, и вызов без аргумента молча давал сумму без налога
 * там, где налог есть. Теперь ставку приходится назвать, а назвать её
 * можно только зная страну контрагента — см. vatBpsFor.
 */
export function withVat(cents: number, bps: number): number {
  return cents + Math.round((cents * bps) / 10_000);
}

