/**
 * Комиссия оператора в базисных пунктах: 300 bps = 3%.
 *
 * Хранится в bps, а не в долях, чтобы не тащить float в расчёты денег.
 * В будущем комиссия станет гибкой по клиентам и типам заказов — тогда это
 * значение станет дефолтом, а действующая ставка будет приходить из БД.
 *
 * ВАЖНО: при закрытии рейса действующая ставка фиксируется в самой записи рейса.
 * Отчёты и счета считают по зафиксированной ставке, а не по текущей — иначе
 * изменение комиссии перепишет задним числом уже выставленные счета.
 */
/*
 * ВРЕМЕННО 0 на время проверки — вместе с app.current_commission_bps() в
 * базе, которая и есть действующий источник. По ТЗ §1 ставка 3%, вернуть
 * оба значения нужно до первых настоящих расчётов.
 */
export const COMMISSION_BPS = 0;

/**
 * Ставка ALV (финского НДС) в базисных пунктах: 2550 = 25,5%.
 *
 * Все суммы в системе — БЕЗ налога. Ставка заказчика, комиссия, выплата
 * перевозчику, недельные итоги: везде нетто. Налог добавляется в счёте,
 * а не в расчётах платформы, потому что ставка меняется решением
 * государства (25,5% действует с 1 сентября 2024 года), а закрытые рейсы
 * пересчитывать задним числом нельзя — по той же причине, по которой
 * комиссия замораживается в записи рейса.
 *
 * Интерфейс обязан говорить об этом прямо: 754 € и 754 € с ALV — разные
 * деньги, и человек, увидевший первое, не должен ждать второго на счёте.
 */
export const VAT_BPS = 2550;

/** Сумма с налогом — для счёта, не для расчётов платформы. */
export function withVat(cents: number, bps: number = VAT_BPS): number {
  return cents + Math.round((cents * bps) / 10_000);
}

/** Комиссия оператора с суммы в центах. */
export function commissionCents(rateCents: number, bps: number = COMMISSION_BPS): number {
  return Math.round((rateCents * bps) / 10_000);
}

/** Выплата перевозчику: ставка заказчика за вычетом комиссии. */
export function payoutCents(rateCents: number, bps: number = COMMISSION_BPS): number {
  return rateCents - commissionCents(rateCents, bps);
}

