import type { TruckProfile } from './types';

/**
 * Профили грузовика по странам.
 *
 * Финляндия — исключение в Европе. Разрешённая полная масса до 76 тонн и
 * длина до 34,5 метра для сцепок HCT, тогда как стандарт ЕС — 40 тонн и
 * 16,5 метра. Один профиль на всю платформу неизбежно врал бы: заданный
 * по-европейски, он уводил бы финскую сцепку с дорог, где она проедет
 * законно; заданный по-фински — давал бы недостоверный маршрут в Швецию
 * или дальше.
 *
 * Поэтому профиль выбирается по стране точки забора. Скандинавия —
 * Финляндия, Швеция, Норвегия, Дания — идёт по одному профилю: это одна
 * и та же сцепка, пересекающая границы. Остальная Европа получает
 * европейский.
 *
 * Значения — типовая сцепка тягач плюс полуприцеп, а не предел закона:
 * маршрут считается до того, как выбран перевозчик, и машина ещё
 * неизвестна. Занижать здесь опаснее, чем завышать: маршрут, посчитанный
 * для лёгкой машины, проведёт фуру там, где она не пройдёт.
 */

/** Типовая финская сцепка. Высота 4,4 м — предел без спецразрешения. */
const FI: TruckProfile = {
  grossWeightKg: 44_000,
  weightPerAxleKg: 8_800,
  heightM: 4.4,
  widthM: 2.55,
  lengthM: 16.5,
  axleCount: 5,
};

/** Стандарт ЕС: 40 тонн, 16,5 метра, высота 4,0 м. */
const EU: TruckProfile = {
  grossWeightKg: 40_000,
  weightPerAxleKg: 8_000,
  heightM: 4.0,
  widthM: 2.55,
  lengthM: 16.5,
  axleCount: 5,
};

const BY_COUNTRY: Record<string, TruckProfile> = {
  FI: FI,
  /* Швеция живёт по тем же нормам, что Финляндия: до 74 тонн и 25,25 м. */
  SE: FI,

  /*
   * Норвегия и Дания — по скандинавскому профилю, а не по европейскому,
   * и это про машину, а не про закон.
   *
   * Из всех параметров TomTom реагует только на высоту — проверено
   * замером, маршрут меняется на 4,8 м и не меняется от массы. А высота
   * у сцепки та же самая по обе стороны границы: финский тягач с 4,4 м
   * не становится четырёхметровым, въехав в Норвегию. Поставить здесь
   * европейские 4,0 м значило бы провести его под мостами, под которые
   * он не пройдёт, — то самое занижение, которое опаснее завышения.
   *
   * Предельные массы у этих стран свои (Норвегия до 50 т, Дания до 48 т)
   * и в профиль не вписаны намеренно: числа не проверены оператором, а
   * поставщик их всё равно не учитывает. Когда появится провайдер,
   * который учитывает, — брать их нужно у оператора, а не отсюда.
   */
  NO: FI,
  DK: FI,
};

/**
 * Профиль по коду страны точки забора.
 *
 * Замер по Финляндии показал, что TomTom учитывает высоту (маршрут
 * меняется с 4,8 м) и не реагирует на массу. Профиль всё равно задаётся
 * полностью: то, что поставщик сегодня игнорирует часть параметров, —
 * свойство его данных, а не нашего описания машины.
 */
export function truckProfile(countryCode?: string | null): TruckProfile {
  if (!countryCode) return FI;
  return BY_COUNTRY[countryCode.toUpperCase()] ?? EU;
}

export { FI as FINNISH_TRUCK, EU as EU_TRUCK };
