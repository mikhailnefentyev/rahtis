/*
 * Про оценку совпадения и почему по ней нельзя ставить порог.
 *
 * Замер показал, что шкала score у TomTom не одна. Геокодер полного
 * адреса возвращает 7,87–10,31 для настоящих адресов и 4,66–6,08 для
 * несуществующих, а подсказка на ту же улицу — 0,99–1,00. Числа
 * несопоставимы между вызовами, и абсолютный порог, снятый с одного
 * из них, забраковал бы все результаты другого.
 *
 * Поэтому доверие определяется типом результата, а не числом: точный
 * адрес с номером дома против центроида индекса или города. Это признак
 * устойчивый и означает ровно то, что нужно знать — стоит ли точка там,
 * где ворота склада, или в середине почтового округа.
 *
 * Оценка при этом сохраняется в order_stops.geocode_score: сравнивать её
 * между однотипными вызовами осмысленно, и при разборе жалобы на маршрут
 * она пригодится.
 */

/**
 * Есть ли вообще расчёт маршрута.
 *
 * Ключа может не быть — в чужой копии проекта, в предпросмотре ветки, при
 * исчерпанном лимите. Это не поломка: километраж вводится вручную, как и
 * до появления роутера, а форма просто не предлагает посчитать. Поэтому
 * проверка отдельной функцией, а не исключением на первом же вызове.
 */
export function routingConfigured(): boolean {
  return Boolean(process.env.TOMTOM_KEY);
}

/**
 * Отпечаток маршрута: страна профиля и координаты точек по порядку.
 *
 * По нему решается, нужен ли пересчёт. Хранится строкой, а не хэшем,
 * намеренно: при разборе жалобы «почему тут 412 км» видно, по каким
 * именно координатам считали, без обратного преобразования.
 *
 * Пять знаков после запятой — примерно метр. Точнее не нужно: адрес,
 * сдвинувшийся на метр, того же маршрута и стоит.
 */
export function routeFingerprint(points: LatLon[], countryCode: string): string {
  const coords = points
    .map((p) => `${p.lat.toFixed(5)},${p.lon.toFixed(5)}`)
    .join(';');

  return `${countryCode}|${coords}`;
}

/** Метры в километры для показа и для distance_km. */
export function metresToKm(metres: number): number {
  return Math.max(1, Math.round(metres / 1000));
}
