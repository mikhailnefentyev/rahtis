import { revalidatePath } from 'next/cache';

/**
 * Что пересобрать после изменения заказа.
 *
 * Здесь оно перечислено один раз, а не пишется заново в каждом действии.
 * Прежде почти все звали `revalidatePath('/fi', 'layout')` — сброс всего
 * поддерева локали. Заказ трогает две страницы, а сбрасывались все:
 * витрина, условия, оба кабинета, админка.
 *
 * Цена этого видна не сразу. Страница условий читается из кэша с
 * прошлой недели и меняется раз в месяц; после каждой отметки точки она
 * собиралась заново, вместе с обращением к базе за текстом. Так
 * аккуратно заведённый кэш отменяется чужой строкой в другом файле.
 *
 * Обе стороны в списке намеренно: заказ виден и заказчику, и
 * перевозчику, и обновиться должны оба — статус у них один и тот же
 * (ТЗ §7).
 */
function paths(locale: string): string[] {
  return [
    /* Списки, где заказ лежит строкой. */
    `/${locale}/shipper/orders`,
    `/${locale}/carrier/desk`,
    /* Обзоры кабинетов: там счётчики и последние события. */
    `/${locale}/shipper`,
    `/${locale}/carrier`,
  ];
}

/** Заказ изменился: списки и обзоры обеих сторон. */
export function revalidateOrder(locale: string): void {
  for (const path of paths(locale)) revalidatePath(path);
}

/**
 * Рейс закрыт или отменён — он уходит из рабочих списков и появляется
 * среди выполненных. Вкладки «выполненные» добавляются к обычному
 * набору: без них закрытый рейс не появился бы там до следующего
 * захода с обновлением.
 */
export function revalidateOrderFinished(locale: string): void {
  for (const path of [...paths(locale), `/${locale}/shipper/done`, `/${locale}/carrier/done`]) {
    revalidatePath(path);
  }
}
