/**
 * Цена, следующая за пробегом.
 *
 * Отдельным модулем, а не рядом с действиями: считает и браузер, и
 * сервер. Экран показывает заказчику «было 836 км / 900 €, стало 937 км /
 * 1008 €» до нажатия, и это должно быть то же число, которое потом ляжет
 * в базу. Две реализации разошлись бы на первом же округлении.
 *
 * Файл намеренно без 'use server': там функция стала бы серверным
 * действием, и подсказка цены при наборе километров ходила бы по сети на
 * каждую клавишу.
 */

/**
 * Ставка после изменения пробега.
 *
 * Сохраняется не сумма, а цена километра: договаривались о €/км, и
 * маршрут, ставший длиннее на сто километров, стоит ровно на сто
 * километров дороже.
 *
 * Пропорцией, а не хранимой ставкой за километр. Ставка в целых центах
 * округлилась бы при записи, и обратное умножение сдвинуло бы сумму:
 * 900 € за 836 км — это 107,655 цента за километр, а не 108. Одно
 * округление в конце вместо двух по дороге.
 *
 * Ноль возвращается там, где считать не из чего: пустое поле в форме —
 * обычное состояние набора, а не ошибка, и падать на нём незачем.
 */
export function repricedRateCents(rateCents: number, fromKm: number, toKm: number): number {
  if (!Number.isFinite(rateCents) || !Number.isFinite(fromKm) || !Number.isFinite(toKm)) return 0;
  if (rateCents <= 0 || fromKm <= 0 || toKm <= 0) return 0;

  return Math.max(1, Math.round((rateCents * toKm) / fromKm));
}
