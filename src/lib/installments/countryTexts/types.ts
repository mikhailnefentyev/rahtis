/**
 * Тексты кабинета, которые зависят от страны сделки (23.11.2026): кто
 * продаёт и покупает, по какому праву договор, пороги просрочки, что
 * сделать до передачи, что после полной оплаты и что значит запись о
 * прекращении. У Финляндии таких записей нет — её тексты в copy.ts и
 * i18n/* остаются как были.
 *
 * Термины права страны (vastutav kasutaja, turētājs, kohtutäitur…) — из
 * словаря интерфейса в docs/equipment-sale/countries/ и стоят в скобках на
 * языке страны: по ним сторона ищет услугу в своём реестре.
 */
export type InstallmentLawCopy = {
  /** Вступление раздела у перевозчика и у компании без парка. */
  intro: string;
  introSeller: string;
  /** Кто может продавать и покупать. */
  notAllowed: string;
  /** Подпись ссылки на договор — с языком договора. */
  contract: string;
  /** Что сделать до передачи: реестр, страховка, лицензия. */
  nextSteps: string;
  /** Оговорка о счёте: PDF и электронный счёт страны. */
  invoiceNote: string;
  /** Пороги рядом с расчётом: {tenth}, {twentieth}, {needed}. */
  thresholdsText: string;
  /** Заголовок сигнала продавцу: {plate}. */
  thresholdTitle: string;
  /** Что значит достигнутый порог — сигнал продавцу и плашка на странице сделки. */
  threshold: string;
  /** Пункты чек-листа передачи: запись в реестре и страховка. */
  checkRegister: string;
  checkInsurance: string;
  /**
   * Пункты чек-листа, которых у других стран нет, — перед записью в реестре
   * (23.11.2026). Дания: оговорка о собственности подана на регистрацию в
   * Bilbogen до передачи. Нет поля — чек-лист той же длины, что основной.
   */
  checkBefore?: string[];
  /**
   * Подсказка у ставки процентов, если у страны она своя (23.11.2026):
   * Швеция — проценты не предлагаются и почему; Дания — проценты отдельной
   * строкой с суммой. Нет поля — общая подсказка (COMMON_TEXTS).
   */
  rateHint?: string;
  /** После полной оплаты: переход права собственности и реестр. */
  afterPaid: string;
  /** Запись о прекращении: когда её ставить. */
  terminationHint: string;
  /** Причина «продавец вернул машину» — словами права страны. */
  reasonRepossessed: string;
  /** Чей взаиморасчёт после прекращения. */
  settlement: string;
};

/** Одинаковое для всех стран, кроме Финляндии, — по языкам. */
export type InstallmentCommonCopy = {
  /** Досрочное погашение: {sum}. В договорах Эстонии и Латвии это п. 4.6. */
  payoff: string;
  /** Подсказка у ставки процентов. */
  rateHint: string;
  /** Начало фразы «оплачено {date}.» на странице сделки. */
  paidOn: string;
  /** Начало уведомления «все платежи внесены». */
  allPaid: string;
};
