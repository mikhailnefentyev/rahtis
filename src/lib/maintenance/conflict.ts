/**
 * Отказ базы «вне работы в дни заказа» (app.asset_order_conflict).
 *
 * Помощники требований возвращают текст, и вызывающие функции поднимают
 * его с общим кодом 55003 «машина не подходит». Чтобы перевозчик видел
 * настоящую причину — машина в сервисе или с дефектом, — а не «не тот
 * кузов», сайт узнаёт этот отказ по началу текста. Без зависимостей:
 * модуль читают и серверные действия, и тесты.
 */
export function isDowntimeConflict(error: { message?: string | null } | null | undefined): boolean {
  return Boolean(error?.message && error.message.includes('Вне работы'));
}
